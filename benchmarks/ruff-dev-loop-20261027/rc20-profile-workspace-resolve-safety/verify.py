def normalized_typed(text,i,expected,contexts):
    items=list(map(json.loads,text.splitlines()))
    if i in ERRORS:
        need(items==[],'stdout on failure')
        return items
    need([r["reason"] for r in items]==["compiler-artifact","build-script-executed","compiler-artifact","build-finished"],
         (i,"typed order"))
    build,script,app,finished=items
    need(finished=={"reason":"build-finished","success":True},(i,"success message"))
    need(build["target"]["name"]=="build-script-build" and app["target"]["name"]=="profile_probe","target identity")
    need(build["fresh"]==(i not in FULL) and app["fresh"]==(i not in FULL|MAIN),(i,"artifact freshness"))
    for r in (build,app):
        need(r["profile"]["debug_assertions"]==(expected.startswith("true")) and
             r["features"]==(["new"] if i==16 else []),(i,"applied profile or selection"))
    need(app["executable"]=="<arena>/target/debug/profile_probe" and app["filenames"]==[app["executable"]],(i,"runtime path"))
    need(script["env"]==[["RAW_PROFILE_VALUE",expected.split()[1]]],(i,"build-script env"))
    for parent,key,suffix in ((build["filenames"],0,"/out/build_script_build"),(script,"out_dir","/out")):
        m=NS.fullmatch(parent[key])
        need(m and m[3].endswith(suffix),(i,"build script output path"))
        contexts.add(m[2])
        parent[key]=m[1]+"<workspace-and-cargo-namespace>"+m[3]
    return items


def checked_visit(r,arm,i,manifest,snapshots,contexts):
    error=i in ERRORS
    expected_text="true 17" if i in {1,2,3,4,18,19} else "false 17" if i==5 else "false 29"
    elf=OLD if expected_text=="true 17" else ACTIVE if i==5 else FEATURE if i==16 else EDITED
    expected_lock="version = [\n" if i==17 else LOCK
    hit=i in {2,7,9,19} or (arm=="B" and i in {3,4,5,6,10})
    need(r["exit"]==(101 if error else 0) and r["hit"]==hit and
         r["manifest"]==sha(manifest) and r["lock"]==sha(expected_lock),(arm,i,"verdict/input"))
    need(r["public_stdout_sha256"]==sha(r["stdout_text"]) and r["public_stderr_sha256"]==sha(r["stderr_text"]),
         (arm,i,"full exported Cargo streams"))
    if snapshots:
        need(r["manifest_bytes"]==manifest and r["lock_bytes"]==expected_lock and
             r["marker_bytes"]==r["marker"],(arm,i,"original input and marker bytes"))
    need(re.fullmatch("[0-9a-f]{16}",r["marker"]) is not None,(i,"marker contents"))
    diag=ERRORS[i] if error else (WARNING if i==10 else "")+(COMPILING if i in FULL|MAIN else "")+FINISHED
    need(r["user_diagnostic"]==diag==P["user_diagnostics"](r["stderr_text"]),(arm,i,"complete user diagnostic"))
    need(("reusing the cached workspace resolution" in r["stderr_text"])==hit,(arm,i,"cache message"))
    if error:
        need("output" not in r and "elf" not in r and r["stdout"]==sha(b"") and r["stdout_text"]=="",
             (arm,i,"unsuccessful work emitted a result"))
    else:
        need(r["output"]==expected_text and r["elf"]==elf,(arm,i,"actual printed value and entire ELF"))
        if snapshots:
            need(r["runtime_stdout_sha256"]==sha(expected_text+"\n"),(arm,i,"runtime stream"))
    typed=normalized_typed(r["stdout_text"],i,expected_text,contexts)
    compiles=["profile_probe","build_script_build"] if i in FULL else ["profile_probe"] if i in MAIN else []
    links=len(compiles)
    events=r["native"]
    roles=[]
    for e in events:
        need(e["lines"][0]<=e["lines"][1] and all(re.fullmatch("[0-9a-f]{64}",e[k]) for k in
             ("argv_sha256","raw_program_path_sha256")), (arm,i,"kernel path and argv"))
        if N["is_compile"](e): role="compile:"+e["crate"]
        elif N["is_link"](e):
            need(e["program"]=="ld.bfd" and e["linker_sha256"]==WILD,(arm,i,"stock Wild"))
            role="link"
        elif e["program"]=="build_script_build": role="build-script"
        else: role="other"
        roles.append([e["program"],role])
    need(r["events"]==roles and r["roles"]==[role for _,role in roles if role!="other"],(arm,i,"kernel-vs-worker counts"))
    need(Counter(r["roles"])==Counter(["compile:"+n for n in compiles]+["link"]*links+
         (["build-script"] if compiles else [])),(arm,i,"native work changed"))
    flags=["--profile","nonexistent"] if i==9 else ["--features","new"] if i in (15,16) else []
    args=["build","-p","profile_probe","--locked","--offline","--message-format=json",*flags]
    need([(e["program"],e["cargo_args"])for e in events[:2]]==[("cargo",["+ohm",*args]),("cargo",args)],(i,"actual Cargo argv"))
    need([e["program"]for e in events].count("cc")==[e["program"]for e in events].count("collect2")==links,
         (i,"driver counts"))
    dirty=[] if error else sorted(n for n,on in [("build-script-build",i in FULL),("profile_probe",i in FULL|MAIN)] if on)
    need(r.get("dirty",[])==dirty,(arm,i,"dirty target census"))
    return typed,Counter((e["program"],e["crate"])for e in events),diag,r.get("elf"),r.get("output")


def check_all(data):
    labels=[f"{i:02}-{name}" for i,name in enumerate(STAGES,1)]
    expected_manifest=manifests()
    need(tomllib.loads(expected_manifest[10])["dependencies"]==tomllib.loads(expected_manifest[11])["dependencies"] and
         expected_manifest[10].index("[dependencies]")>expected_manifest[10].index("[profile.dev]") and
         expected_manifest[11].index("[dependencies]")<expected_manifest[11].index("[profile.dev]"),"both dependency positions")
    need("[profile.fake]" in tomllib.loads(expected_manifest[0])["package"]["description"] and
         "new" in tomllib.loads(expected_manifest[15])["features"],"fake header / feature")
    previous=None
    for kind in ("original","replay"):
        sample=data[kind];terminal=sample["terminal"]
        need(terminal["images"]==IMAGES and sample["snapshots"]==(kind=="replay"),"physical input enrollment")
        need(sha(json.dumps(terminal,sort_keys=True,indent=2)+"\n")==sample["terminal_sha256"],"native controller terminal")
        if kind=="replay":
            need(sample["physically_rehashed_elf_bytes"]=={x:434152 for x in (OLD,ACTIVE,EDITED,FEATURE)},"physical ELF sizes and hashes")
        current={}
        workspaces={}
        for arm in "AB":
            rows=sample["arms"][arm];contexts=set()
            need(sorted(rows)==labels and len(terminal["scopes"])==len(labels), "all 19 real calls")
            classes=([1,1,3,1,5,6,6,6,6,10,10,10,10,10,10,16,16,1,1] if arm=="A" else [1]*15+[16,16,1,1])
            representatives={}
            for i,tag in enumerate(labels,1):
                record=rows[tag];out=checked_visit(record,arm,i,expected_manifest[i-1],kind=="replay",contexts)
                if tag in current:need(current[tag]==out,(kind,arm,tag,"entire normalized stdout, diagnostic and kernel role equality"))
                current[tag]=out
                marker=record["marker"];key=classes[i-1]
                if key in representatives:need(representatives[key]==marker,(arm,i,"marker was unexpectedly replaced"))
                else:need(marker not in representatives.values(),(arm,i,"distinct input reused a marker"));representatives[key]=marker
                t=terminal["scopes"][i-1]
                need(t["stage"]==tag and t["exit"]==record["exit"] and
                     t["control_hit" if arm=="A" else "candidate_hit"]==record["hit"] and
                     t["roles"]==sorted(record["roles"]) and t["output"]==record.get("output") and t["elf"]==record.get("elf"),
                     (arm,i,"native terminal census"))
            need(len(contexts)==1,(arm,"one fixed native workspace and Cargo namespace"))
            workspaces[arm]=contexts.pop().split("/")
        need(workspaces["A"][0]==workspaces["B"][0] and workspaces["A"][1]!=workspaces["B"][1],
             "only authenticated tool namespace changes between arms")
        if previous is not None:need(previous==current,"original versus new clean native replay")
        previous=current


def check_index(sample,files):
    claims={"complete.json":sample["terminal_sha256"]}
    if sample["snapshots"]:
        for digest,size in sample["physically_rehashed_elf_bytes"].items():
            need(files["elf/"+digest]["bytes"]==size,"physical ELF length")
            claims["elf/"+digest]=digest
    for arm,visits in sample["arms"].items():
        for tag,r in visits.items():
            prefix=f"{arm}/{tag}/"
            for f,k in (("stdout","stdout"),("stderr","stderr"),("exec","trace"),("row.json","raw_row_sha256")):
                claims[prefix+f]=r[k]
            if sample["snapshots"]:
                for f,k in (("Cargo.lock","lock"),("Cargo.toml","manifest"),("marker","marker_bytes")):
                    claims[prefix+f]=sha(r[k]) if f=="marker" else r[k]
                if r["exit"]==0:claims[prefix+"runtime.stdout"]=r["runtime_stdout_sha256"]
    need(set(files)==set(claims) and all(files[p]["sha256"]==v for p,v in claims.items()),"all private originals bound")


def mutations(data):
    def reject(name,edit):
        v=copy.deepcopy(data)
        edit(v["replay"]["arms"]["B"])
        try:check_all(v)
        except (ValueError,KeyError):return
        raise ValueError("accepted mutation: "+name)
    reject("warning span",lambda r:r["14-invalid-profile"].update(user_diagnostic=ERRORS[14].replace(":24:13",":24:14")))
    reject("ignored native rebuild",lambda r:r["06-script-value"]["native"].pop(-1))
    reject("wrong clean executable",lambda r:r["08-clean-edited"].update(elf=ACTIVE))
    reject("accepted hidden dependency",lambda r:r["12-earlier-dependency"].update(hit=True))
    reject("unrelated target name",lambda r:r["01-seed"].update(stdout_text=r["01-seed"]["stdout_text"].replace("/out/build_script_build","/out/wrong")))
    reject("replaced marker",lambda r:r["03-inactive"].update(marker="1"*16,marker_bytes="1"*16))
    reject("truncated malformed diagnostic",lambda r:r["17-malformed-lock"].update(stderr_text="error: failed to parse lock file\n"))
    reject("changed source bytes",lambda r:r["06-script-value"].update(manifest_bytes=r["05-active"]["manifest_bytes"]))
    reject("wrong runtime stream",lambda r:r["06-script-value"].update(runtime_stdout_sha256=sha("false 17\n")))


