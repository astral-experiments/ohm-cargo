//! Revalidates private artifacts after a build script runs in a seeded worktree.

use std::fs;
use std::io::Read;
use std::path::Path;
use std::sync::atomic::Ordering;

use cargo_util::{ProcessBuilder, paths};
use filetime::FileTime;

use super::{BuildState, Fingerprint, LocalFingerprint, find_stale_file, parse_dep_info};
use crate::CargoResult;
use crate::core::compiler::{BuildOutput, OHM_WORKTREE_SEED_DENY_MARKER, OHM_WORKTREE_SEED_MARKER};
use crate::util;
use crate::util::data_structures::HashMap;

/// A completed script result and its generation, independent of execution freshness.
pub(crate) const OHM_WORKTREE_SCRIPT_RESULT: &str = ".ohm-worktree-result-v1";
/// A transplanted script must execute before any consumer may reuse its result.
pub(crate) const OHM_WORKTREE_SCRIPT_RERUN: &str = ".ohm-worktree-rerun";

#[derive(Clone)]
pub(super) struct ScriptResult {
    digest: blake3::Hash,
    pub(super) generation: FileTime,
    pub(super) unchanged_after_run: bool,
}

impl ScriptResult {
    pub(super) fn dependency_hash(&self) -> u64 {
        util::hash_u64(("ohm-worktree-script-result-v1", self.digest.as_bytes()))
    }
}

/// Accepts a recorded result only while its stdout and generated bytes still match.
pub(super) fn load_script_result(
    path: &Path,
    stdout: &Path,
    out_dir: &Path,
    output: &BuildOutput,
) -> Option<ScriptResult> {
    let metadata = fs::symlink_metadata(path).ok()?;
    if !metadata.is_file() {
        return None;
    }
    let digest = result_digest(stdout, out_dir, output).ok()??;
    if fs::read(path).ok()? != result_contents(digest) {
        return None;
    }
    Some(ScriptResult {
        digest,
        generation: FileTime::from_last_modification_time(&metadata),
        unchanged_after_run: false,
    })
}

/// Commits a successful result without changing its generation when content is identical.
pub(super) fn record_script_result(
    path: &Path,
    stdout: &Path,
    out_dir: &Path,
    output: &BuildOutput,
    previous: Option<&ScriptResult>,
) -> CargoResult<Option<ScriptResult>> {
    let Some(digest) = result_digest(stdout, out_dir, output).ok().flatten() else {
        if path.symlink_metadata().is_ok() {
            paths::remove_file(path)?;
        }
        return Ok(None);
    };
    let contents = result_contents(digest);
    let same_record = fs::symlink_metadata(path).is_ok_and(|metadata| metadata.is_file())
        && fs::read(path).is_ok_and(|old| old == contents);
    if !same_record {
        paths::write_atomic(path, contents)?;
    }
    Ok(Some(ScriptResult {
        digest,
        generation: paths::mtime(path)?,
        unchanged_after_run: same_record
            && previous.is_some_and(|previous| previous.digest == digest),
    }))
}

fn result_contents(digest: blake3::Hash) -> Vec<u8> {
    format!("{}\n", digest.to_hex()).into_bytes()
}

/// Native outputs outside OUT_DIR are opaque; retain ordinary invalidation for them.
fn result_digest(
    stdout: &Path,
    out_dir: &Path,
    output: &BuildOutput,
) -> CargoResult<Option<blake3::Hash>> {
    if !output.library_paths.is_empty()
        || !output.library_links.is_empty()
        || !output.linker_args.is_empty()
        || !fs::symlink_metadata(stdout)?.is_file()
        || !fs::symlink_metadata(out_dir)?.is_dir()
    {
        return Ok(None);
    }
    let mut hasher = blake3::Hasher::new();
    // Raw output also captures unknown directives. Parsed output catches changes
    // in Cargo's interpretation, including relocation of synthesized env values.
    hasher.update(&util::hash_u64(output).to_le_bytes());
    hash_file(&mut hasher, stdout)?;
    if !hash_tree(&mut hasher, out_dir, out_dir)? {
        return Ok(None);
    }
    Ok(Some(hasher.finalize()))
}

/// Hashes the complete regular-file tree, including names and modes but never mtimes.
fn hash_tree(hasher: &mut blake3::Hasher, root: &Path, directory: &Path) -> CargoResult<bool> {
    let mut entries = fs::read_dir(directory)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        let metadata = fs::symlink_metadata(&path)?;
        if !metadata.is_dir() && !metadata.is_file() {
            return Ok(false);
        }
        let name = paths::path2bytes(path.strip_prefix(root)?)?;
        hasher.update(&(name.len() as u64).to_le_bytes());
        hasher.update(name);
        hasher.update(&[u8::from(metadata.is_dir())]);
        hasher.update(&[u8::from(metadata.permissions().readonly())]);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            hasher.update(&(metadata.permissions().mode() & 0o777).to_le_bytes());
        }
        if metadata.is_dir() {
            if !hash_tree(hasher, root, &path)? {
                return Ok(false);
            }
        } else {
            hash_file(hasher, &path)?;
        }
    }
    Ok(true)
}

fn hash_file(hasher: &mut blake3::Hasher, path: &Path) -> CargoResult<()> {
    let mut file = fs::File::open(path)?;
    hasher.update(&file.metadata()?.len().to_le_bytes());
    let mut buffer = [0_u8; 16384];
    loop {
        let len = file.read(&mut buffer)?;
        if len == 0 {
            break;
        }
        hasher.update(&buffer[..len]);
    }
    Ok(())
}

/// Rechecks the complete inputs after scripts finish, separately from metadata-only cutoff.
pub(in crate::core::compiler) fn can_reuse_after_scripts(
    fingerprint: &Fingerprint,
    pkg_root: &Path,
    build_root: &Path,
    namespace: &Path,
    rustc_dep_info: &Path,
    rustc: &ProcessBuilder,
) -> bool {
    let Some(expected) = fingerprint.worktree_reuse_hash.lock().unwrap().clone() else {
        return false;
    };
    if !namespace.join(OHM_WORKTREE_SEED_MARKER).is_file()
        || namespace
            .join(OHM_WORKTREE_SEED_DENY_MARKER)
            .symlink_metadata()
            .is_ok()
    {
        return false;
    }
    let mut unchanged_dependency = false;
    for dependency in &fingerprint.deps {
        match dependency.fingerprint.build_state() {
            BuildState::Fresh => {}
            BuildState::SkippedEarlyCutoff
                if dependency
                    .fingerprint
                    .worktree_reused
                    .load(Ordering::Acquire) =>
            {
                unchanged_dependency = true;
            }
            BuildState::BuiltChanged
                if dependency
                    .fingerprint
                    .script_result
                    .lock()
                    .unwrap()
                    .as_ref()
                    .is_some_and(|result| result.unchanged_after_run) =>
            {
                unchanged_dependency = true;
            }
            // BuiltUnchanged and ordinary SkippedEarlyCutoff only prove metadata
            // reuse; a transitive dependency's link artifacts can still change.
            _ => return false,
        }
    }
    fingerprint.clear_memoized();
    if !unchanged_dependency
        || util::to_hex(fingerprint.hash_u64()) != expected
        || fingerprint.outputs.is_empty()
        || fingerprint.outputs.iter().any(|path| !path.is_file())
    {
        return false;
    }

    let Ok(raw) = super::parse_rustc_dep_info(rustc_dep_info) else {
        return false;
    };
    if raw.files.is_empty()
        || raw.env.iter().any(|(key, previous)| {
            let current = rustc.get_env(key);
            match current.as_ref() {
                Some(value) => value
                    .to_str()
                    .is_none_or(|value| Some(value) != previous.as_deref()),
                None => previous.is_some(),
            }
        })
    {
        return false;
    }

    // Never reuse the preparation-time cache: the script may have changed a
    // generated file or even package source, including backdating its mtime.
    let mut mtimes = HashMap::default();
    let mut checksums = HashMap::default();
    let local = fingerprint.local.lock().unwrap();
    if local.is_empty() {
        return false;
    }
    local.iter().all(|local| {
        let LocalFingerprint::CheckDepInfo {
            dep_info,
            checksum: true,
        } = local
        else {
            return false;
        };
        let dep_info = build_root.join(dep_info);
        let Ok(Some(info)) = parse_dep_info(pkg_root, build_root, &dep_info) else {
            return false;
        };
        !info.files.is_empty()
            && find_stale_file(
                &mut mtimes,
                &mut checksums,
                &dep_info,
                info.files.iter().map(|(path, checksum)| (path, *checksum)),
                true,
            )
            .is_none()
    })
}
